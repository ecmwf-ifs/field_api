PROGRAM GATHER_SCATTER_COLLAPSE2

USE FIELD_MODULE
USE FIELD_FACTORY_MODULE
USE FIELD_ACCESS_MODULE
USE FIELD_GATHSCAT_COLLAPSE2_MODULE
USE PARKIND1
USE FIELD_ABORT_MODULE

IMPLICIT NONE

INTEGER (KIND=JPIM), PARAMETER :: NPROMA = 10, NGPBLKS = 4, NFLEVG = 10, NFLD = 5, NGPTOT = NPROMA * NGPBLKS - 4
INTEGER (KIND=JPIM), PARAMETER :: NMISS = -99999, NNEW = 22222
INTEGER (KIND=JPIM), PARAMETER :: NLEV0 = 0, NLEV1 = NFLEVG+1


TYPE (FIELD_GATHSCAT_COLLAPSE2) :: YL_FGS

LOGICAL :: LLTRIG (NPROMA, NFLEVG, NGPBLKS)
CLASS (FIELD_3LM), POINTER :: YLTRIG => NULL ()

INTEGER (KIND=JPIM), ALLOCATABLE :: ID (:,:,:,:)
CLASS (FIELD_4IM), POINTER :: YLFID => NULL()
INTEGER (KIND=JPIM),POINTER :: IDPTR_FILTERED (:,:,:) => NULL (), IDPTR (:,:,:,:) => NULL ()

INTEGER (KIND=JPIM), ALLOCATABLE :: ID1 (:,:,:,:)
CLASS (FIELD_4IM), POINTER :: YLFID1 => NULL()
INTEGER (KIND=JPIM),POINTER :: ID1PTR_FILTERED (:,:,:) => NULL (), ID1PTR (:,:,:,:) => NULL ()

INTEGER (KIND=JPIM) :: JLON, JBLK, JLEV, JFLD, IIDIA, IFDIA, JPASS, IVALID, ISIZE

INTEGER (KIND=JPIM) :: FUNC

FUNC (JLON, JLEV, JFLD, JBLK) = (JBLK-1) * NPROMA + (JLON-1) + NGPTOT * (JLEV-1 + NFLEVG * (JFLD-1))


DO JPASS = 1, 2 ! 1=CPU, 2=GPU

! fill condition array

LLTRIG = .FALSE.

DO JBLK = 1, NGPBLKS
  IIDIA = 1 
  IFDIA = MERGE (NPROMA, NGPTOT - (JBLK - 1) * NPROMA, JBLK < NGPBLKS)
  DO JLEV = 1, NFLEVG
     DO JLON = IIDIA, IFDIA
       LLTRIG (JLON,JLEV,JBLK) = MOD (JLON+JLEV, 2) == 0
     ENDDO
  ENDDO
ENDDO

CALL FIELD_NEW (YLTRIG, DATA=LLTRIG)

ALLOCATE(ID (NPROMA, NFLEVG, NFLD, NGPBLKS))

! fill data array

DO JBLK = 1, NGPBLKS
  IIDIA = 1
  IFDIA = MERGE (NPROMA, NGPTOT - (JBLK - 1) * NPROMA, JBLK < NGPBLKS)
  DO JFLD = 1, NFLD
    DO JLEV = 1, NFLEVG
      DO JLON = IIDIA, IFDIA
        ID (JLON, JLEV, JFLD, JBLK) = FUNC (JLON, JLEV, JFLD, JBLK)
      ENDDO
      DO JLON = IFDIA+1, NPROMA
        ID (JLON, JLEV, JFLD, JBLK) = NMISS
      ENDDO
    ENDDO
  ENDDO
ENDDO

! Field with extra levels (top & bottom)

CALL FIELD_NEW (YLFID, DATA=ID)

ALLOCATE(ID1 (NPROMA, NLEV0:NLEV1, NFLD, NGPBLKS))

! fill data array

DO JBLK = 1, NGPBLKS
  IIDIA = 1
  IFDIA = MERGE (NPROMA, NGPTOT - (JBLK - 1) * NPROMA, JBLK < NGPBLKS)
  DO JFLD = 1, NFLD
    ID1 (:, NLEV0, JFLD, JBLK) = NMISS
    ID1 (:, NLEV1, JFLD, JBLK) = NMISS
    DO JLEV = 1, NFLEVG
      DO JLON = IIDIA, IFDIA
        ID1 (JLON, JLEV, JFLD, JBLK) = FUNC (JLON, JLEV, JFLD, JBLK)
      ENDDO
      DO JLON = IFDIA+1, NPROMA
        ID1 (JLON, JLEV, JFLD, JBLK) = NMISS
      ENDDO
    ENDDO
  ENDDO
ENDDO

CALL FIELD_NEW (YLFID1, DATA=ID1, LBOUNDS=[1, NLEV0, 1, 1])

CALL YL_FGS%INIT (YLTRIG, NGPTOT)

IVALID = COUNT (LLTRIG)

! get pointer on filtered data

IF (JPASS == 1) THEN
  IDPTR_FILTERED => GATHER_HOST_DATA_RDWR (YL_FGS, YLFID)
  ID1PTR_FILTERED => GATHER_HOST_DATA_RDWR (YL_FGS, YLFID1)
ELSE
  IDPTR_FILTERED => GATHER_DEVICE_DATA_RDWR (YL_FGS, YLFID)
  ID1PTR_FILTERED => GATHER_DEVICE_DATA_RDWR (YL_FGS, YLFID1)
ENDIF

! Check sizes

ISIZE = SIZE (IDPTR_FILTERED, 1) * SIZE (IDPTR_FILTERED, 3)

IF (.NOT. ((IVALID <= ISIZE) .AND. (ISIZE < IVALID + NPROMA))) THEN
  PRINT *, IVALID
  PRINT *, ISIZE
  PRINT *, IVALID + NPROMA
  CALL FIELD_ABORT ("ERROR")
ENDIF

ISIZE = SIZE (ID1PTR_FILTERED, 1) * SIZE (ID1PTR_FILTERED, 3)

IF (.NOT. ((IVALID <= ISIZE) .AND. (ISIZE < IVALID + NPROMA))) THEN
  PRINT *, IVALID
  PRINT *, ISIZE
  PRINT *, IVALID + NPROMA
  CALL FIELD_ABORT ("ERROR")
ENDIF

! update filtered data
! NB: the update is intentionally split into an explicit device branch
! (JPASS == 2) and a host branch (JPASS == 1) instead of using a single
! offload region with an "IF (JPASS == 2)" clause. nvhpc 24.5 crashes in
! LLVM codegen ("use of undefined value '%L.LB1_...'") when it has to emit
! the host-fallback copy of this region generated by the IF clause.

IF (JPASS == 2) THEN

#ifdef OMPGPU
!$OMP TARGET
#else
!$ACC SERIAL PRESENT (IDPTR_FILTERED, ID1PTR_FILTERED) COPYIN (YL_FGS)
#endif

DO JBLK = 1, YL_FGS%KGPBLKS
  IIDIA = 1
  IFDIA = MERGE (YL_FGS%KLON, YL_FGS%KGPTOT - (JBLK - 1) * YL_FGS%KLON, JBLK < YL_FGS%KGPBLKS)
  DO JFLD = 1, NFLD
    DO JLON = IIDIA, IFDIA
      IDPTR_FILTERED (JLON, JFLD, JBLK) = NNEW
      ID1PTR_FILTERED (JLON, JFLD, JBLK) = NNEW
    ENDDO
    DO JLON = IFDIA+1, YL_FGS%KLON
      IDPTR_FILTERED (JLON, JFLD, JBLK) = NMISS
      ID1PTR_FILTERED (JLON, JFLD, JBLK) = NMISS
    ENDDO
  ENDDO
ENDDO

#ifdef OMPGPU
!$OMP END TARGET
#else
!$ACC END SERIAL
#endif

ELSE

DO JBLK = 1, YL_FGS%KGPBLKS
  IIDIA = 1
  IFDIA = MERGE (YL_FGS%KLON, YL_FGS%KGPTOT - (JBLK - 1) * YL_FGS%KLON, JBLK < YL_FGS%KGPBLKS)
  DO JFLD = 1, NFLD
    DO JLON = IIDIA, IFDIA
      IDPTR_FILTERED (JLON, JFLD, JBLK) = NNEW
      ID1PTR_FILTERED (JLON, JFLD, JBLK) = NNEW
    ENDDO
    DO JLON = IFDIA+1, YL_FGS%KLON
      IDPTR_FILTERED (JLON, JFLD, JBLK) = NMISS
      ID1PTR_FILTERED (JLON, JFLD, JBLK) = NMISS
    ENDDO
  ENDDO
ENDDO

ENDIF

! scatter back

CALL YL_FGS%SCATTER ()

! get data on host for verification

IDPTR => GET_HOST_DATA_RDONLY (YLFID)

DO JBLK = 1, NGPBLKS
  IIDIA = 1 
  IFDIA = MERGE (NPROMA, NGPTOT - (JBLK - 1) * NPROMA, JBLK < NGPBLKS)

  DO JFLD = 1, NFLD
    DO JLEV = 1, NFLEVG

      DO JLON = IIDIA, IFDIA
        IF (LLTRIG (JLON, JLEV, JBLK)) THEN
          IF (IDPTR (JLON, JLEV, JFLD, JBLK) /= NNEW) &
            & CALL FIELD_ABORT ("ERROR")
        ELSE
          IF (IDPTR (JLON, JLEV, JFLD, JBLK) /= FUNC (JLON, JLEV, JFLD, JBLK)) &
            & CALL FIELD_ABORT ("ERROR")
        ENDIF
      ENDDO

      DO JLON = IFDIA+1, NPROMA
        IF (IDPTR (JLON, JLEV, JFLD, JBLK) /= NMISS) &
          & CALL FIELD_ABORT ("ERROR")
      ENDDO
      
    ENDDO
  ENDDO

ENDDO

! extra levels

ID1PTR => GET_HOST_DATA_RDONLY (YLFID1)

DO JBLK = 1, NGPBLKS
  IIDIA = 1 
  IFDIA = MERGE (NPROMA, NGPTOT - (JBLK - 1) * NPROMA, JBLK < NGPBLKS)

  DO JFLD = 1, NFLD
  
    IF (ANY (ID1PTR (:, NLEV0, JFLD, JBLK) /= NMISS)) THEN
       CALL FIELD_ABORT ("ERROR")
    ENDIF

    IF (ANY (ID1PTR (:, NLEV1, JFLD, JBLK) /= NMISS)) THEN
       CALL FIELD_ABORT ("ERROR")
    ENDIF

    DO JLEV = 1, NFLEVG

      DO JLON = IIDIA, IFDIA
        IF (LLTRIG (JLON, JLEV, JBLK)) THEN
          IF (ID1PTR (JLON, JLEV, JFLD, JBLK) /= NNEW) &
            & CALL FIELD_ABORT ("ERROR")
        ELSE
          IF (ID1PTR (JLON, JLEV, JFLD, JBLK) /= FUNC (JLON, JLEV, JFLD, JBLK)) &
            & CALL FIELD_ABORT ("ERROR")
        ENDIF
      ENDDO

      DO JLON = IFDIA+1, NPROMA
        IF (ID1PTR (JLON, JLEV, JFLD, JBLK) /= NMISS) &
          & CALL FIELD_ABORT ("ERROR")
      ENDDO
      
    ENDDO
  ENDDO

ENDDO

! clear data

NULLIFY (IDPTR, ID1PTR)

CALL FIELD_DELETE (YLFID)
CALL FIELD_DELETE (YLFID1)

DEALLOCATE (ID, ID1)

CALL FIELD_DELETE (YLTRIG)

ENDDO

END PROGRAM
